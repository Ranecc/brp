-- V20: P4 credit rider, TPS bonds, quota market (docs/13 §6-8).

-- Credit lines need to know when a human set the limit: auto-recompute must
-- never overwrite a board decision.
ALTER TABLE credit_lines ADD COLUMN limit_pinned BOOLEAN NOT NULL DEFAULT FALSE;

-- Insert-only idem guard for the daily credit job (sweep + interest).
CREATE TABLE credit_accrual_runs (
    run_date  DATE PRIMARY KEY,
    ran_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- TPS bonds (docs/13 §7): the treasury borrows BRC, pays coupons in ticks
-- it actually had — performanceFactor = clamp(threshold / avg_mspt, floor, 1).
CREATE TABLE bond_series (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(64)  NOT NULL,
    face_cents    BIGINT       NOT NULL,
    coupon_pct_annual INT      NOT NULL,
    term_days     INT          NOT NULL,
    total_units   BIGINT       NOT NULL,
    sold_units    BIGINT       NOT NULL DEFAULT 0,
    threshold_mspt DOUBLE      NOT NULL,
    status        VARCHAR(12)  NOT NULL DEFAULT 'OPEN',  -- OPEN|AWARDED|MATURED|REDEEMED|FAILED
    issued_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    matures_at    TIMESTAMP WITH TIME ZONE
);

CREATE TABLE bond_subscriptions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id     BIGINT       NOT NULL,
    tenant_id     VARCHAR(64)  NOT NULL,
    units         BIGINT       NOT NULL,
    filled_cents  BIGINT       NOT NULL,
    coupon_paid_cents BIGINT   NOT NULL DEFAULT 0,
    principal_paid_cents BIGINT NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (series_id, tenant_id)          -- one position per tenant per series
);

CREATE TABLE bond_accruals (
    series_id     BIGINT      NOT NULL,
    tenant_id     VARCHAR(64) NOT NULL,
    accrual_date  DATE        NOT NULL,
    amount_cents  BIGINT      NOT NULL,
    PRIMARY KEY (series_id, tenant_id, accrual_date)
);

-- Quota market (docs/13 §8): order book around the peg anchor, price-time
-- priority, single-transaction settlement, no shorting compute.
CREATE TABLE market_orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     VARCHAR(64) NOT NULL,
    idem_key      VARCHAR(128) NOT NULL UNIQUE,
    side          VARCHAR(4)  NOT NULL,              -- ASK | BID
    qty           BIGINT      NOT NULL,
    qty_remaining BIGINT      NOT NULL,
    price_cents   BIGINT      NOT NULL,              -- BRC cents per quota unit
    status        VARCHAR(12) NOT NULL DEFAULT 'NEW', -- NEW|PARTIAL|FILLED|CANCELLED|EXPIRED
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_market_orders_side ON market_orders (side, status, price_cents, created_at);

CREATE TABLE market_trades (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idem_key      VARCHAR(128) NOT NULL UNIQUE,
    ask_id        BIGINT      NOT NULL,
    bid_id        BIGINT      NOT NULL,
    qty           BIGINT      NOT NULL,
    price_cents   BIGINT      NOT NULL,
    fee_cents     BIGINT      NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
