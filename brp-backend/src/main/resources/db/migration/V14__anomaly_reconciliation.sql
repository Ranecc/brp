-- V14: docs/10 backlog arrivals on the P2 tail:
--   R-2  L1 hot rules + their hits (evaluated on TelemetryServiceImpl.fanOut)
--   R-1  the reconciliation desk's findings (v1: monetary Σ balances ≡ 0)

CREATE TABLE anomaly_rules (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(128) NOT NULL,
    event_type VARCHAR(64)  NOT NULL,
    field      VARCHAR(64)  NOT NULL,   -- payload field, numeric
    op         VARCHAR(4)   NOT NULL,   -- GT | GTE | LT | LTE | EQ
    threshold  DOUBLE       NOT NULL,
    severity   VARCHAR(16)  NOT NULL DEFAULT 'WARN',
    status     VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',   -- ACTIVE | DISABLED
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE anomaly_hits (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id    BIGINT      NOT NULL,
    rule_name  VARCHAR(128) NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    observed   DOUBLE      NOT NULL,
    severity   VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE reconciliation_findings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency        VARCHAR(8) NOT NULL,
    imbalance_cents BIGINT     NOT NULL,   -- Σ balances for the currency; 0 is the only good answer
    status          VARCHAR(16) NOT NULL DEFAULT 'OPEN',   -- OPEN | RESOLVED (by a human, presumably)
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
