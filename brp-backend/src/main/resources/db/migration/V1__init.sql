-- BRP schema v1. Portable DDL (PostgreSQL + H2 in PostgreSQL mode).
--
-- Append-only enforcement for journal_entries (run in production as DBA):
--   REVOKE UPDATE, DELETE ON journal_entries FROM brp_app;
--
-- Note: tenant_id deliberately has no FK to tenants(); tenant isolation is
-- enforced at the service layer today and via PostgreSQL row-level security
-- once RBAC lands (P1). Keeping this loose lets agents bootstrap freely.

CREATE TABLE tenants (
    id         VARCHAR(64)  PRIMARY KEY,
    name       VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE accounts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    VARCHAR(64)  NOT NULL,
    account_no   VARCHAR(64)  NOT NULL,
    account_type VARCHAR(16)  NOT NULL,
    currency     VARCHAR(8)   NOT NULL,
    balance_cents BIGINT      NOT NULL DEFAULT 0,
    version      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_account UNIQUE (tenant_id, account_no)
);

CREATE INDEX idx_accounts_tenant ON accounts (tenant_id);

CREATE TABLE idempotency_keys (
    idem_key      VARCHAR(64) PRIMARY KEY,
    tenant_id     VARCHAR(64) NOT NULL,
    response_json TEXT,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE journal_entries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_id   VARCHAR(64) NOT NULL,
    idem_key     VARCHAR(64) NOT NULL,
    tenant_id    VARCHAR(64) NOT NULL,
    account_id   BIGINT      NOT NULL,
    direction    VARCHAR(6)  NOT NULL,   -- DEBIT | CREDIT
    amount_cents BIGINT      NOT NULL,
    currency     VARCHAR(8)  NOT NULL,
    memo         VARCHAR(256),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_journal_tenant  ON journal_entries (tenant_id);
CREATE INDEX idx_journal_idemkey ON journal_entries (idem_key);

CREATE TABLE ingested_events (
    event_id    VARCHAR(64) PRIMARY KEY,
    agent_id    VARCHAR(64),
    event_type  VARCHAR(64),
    received_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE inventory_snapshots (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    VARCHAR(64)  NOT NULL,
    container_id VARCHAR(128) NOT NULL,
    item_id      VARCHAR(256) NOT NULL,
    amount       BIGINT       NOT NULL,
    captured_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_inv UNIQUE (tenant_id, container_id, item_id)
);

CREATE TABLE signal_commands (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  VARCHAR(64)  NOT NULL,
    channel    VARCHAR(128) NOT NULL,
    level      INT          NOT NULL,   -- 0..15, comparator semantics
    status     VARCHAR(16)  NOT NULL,   -- PENDING | DELIVERED
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_signals_tenant_status ON signal_commands (tenant_id, status);
