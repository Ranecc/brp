-- V18: P3 detection surfaces (docs/12 sections 10-11):
-- wash-cycle findings, price observations, the CPI daily.

CREATE TABLE wash_findings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     VARCHAR(64)  NOT NULL,
    week_of       DATE         NOT NULL,
    accounts_csv  VARCHAR(512) NOT NULL,
    accounts_hash VARCHAR(64)  NOT NULL,
    cycle_len     INT          NOT NULL,
    cycles        INT          NOT NULL,
    score         DOUBLE       NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_wash ON wash_findings (tenant_id, accounts_hash, week_of);

CREATE TABLE price_observations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id     VARCHAR(255) NOT NULL,
    price_cents BIGINT       NOT NULL,
    currency    VARCHAR(8)   NOT NULL DEFAULT 'BRC',
    qty         BIGINT       NOT NULL DEFAULT 1,
    venue       VARCHAR(64),
    source      VARCHAR(16)  NOT NULL DEFAULT 'manual',   -- manual | telemetry
    observed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_price_item ON price_observations (item_id, observed_at);

CREATE TABLE cpi_daily (
    day_stamp   DATE   PRIMARY KEY,   -- "day" is reserved in H2, like its cousin "minute"
    index_value DOUBLE NOT NULL,
    basket_json TEXT,
    captured_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

