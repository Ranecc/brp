-- V15: P3 monetary core (docs/12 sections 2-6) — the shared weekly
-- snapshot, the hysteresis regime, and the two levy ledgers.

CREATE TABLE weekly_snapshots (
    week_of       DATE PRIMARY KEY,             -- ISO week start (Monday)
    gini          DOUBLE      NOT NULL,
    top_share     DOUBLE      NOT NULL,
    regime_after  VARCHAR(8)  NOT NULL,
    captured_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE snapshot_tenants (
    week_of      DATE        NOT NULL,
    tenant_id    VARCHAR(64) NOT NULL,
    wealth_cents BIGINT      NOT NULL,
    velocity     DOUBLE      NOT NULL,
    PRIMARY KEY (week_of, tenant_id)
);

CREATE TABLE policy_regimes (
    name         VARCHAR(32) PRIMARY KEY,       -- 'antitrust'
    state        VARCHAR(8)  NOT NULL,          -- ACTIVE | INACTIVE
    entered_at   TIMESTAMP WITH TIME ZONE,
    last_reading DOUBLE      NOT NULL DEFAULT 0,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Compute levy minute rows (P3-04): insert-only idem, units accumulate at ingest.
CREATE TABLE levy_minutes (
    minute_bucket TIMESTAMP  NOT NULL,          -- truncated minute ("minute" is reserved in H2)
    tenant_id    VARCHAR(64) NOT NULL,
    units        DOUBLE      NOT NULL DEFAULT 0,
    share_pct    DOUBLE      NOT NULL DEFAULT 0,
    amount_cents BIGINT      NOT NULL DEFAULT 0,
    posted       BOOLEAN     NOT NULL DEFAULT FALSE,
    PRIMARY KEY (minute_bucket, tenant_id)
);

-- Wealth levy weekly assessments: insert-only idem per (week, tenant).
CREATE TABLE wealth_assessments (
    week_of       DATE        NOT NULL,
    tenant_id     VARCHAR(64) NOT NULL,
    bracket_cents BIGINT      NOT NULL,
    surcharge     BOOLEAN     NOT NULL DEFAULT FALSE,
    amount_cents  BIGINT      NOT NULL,
    posted        BOOLEAN     NOT NULL DEFAULT FALSE,
    PRIMARY KEY (week_of, tenant_id)
);

