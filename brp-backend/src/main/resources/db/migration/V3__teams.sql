ALTER TABLE saga_instances ADD COLUMN payload TEXT;

-- source: NATIVE (BRP is the authority) | FTBTEAMS (game-side mod is the
-- authority; backend materializes a read-only mirror)
CREATE TABLE teams (
    id         VARCHAR(64) PRIMARY KEY,
    name       VARCHAR(64) NOT NULL,
    tag        VARCHAR(16),
    source     VARCHAR(16) NOT NULL DEFAULT 'NATIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE team_members (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id     VARCHAR(64) NOT NULL,
    player_uuid VARCHAR(64) NOT NULL,
    role        VARCHAR(16) NOT NULL,   -- OWNER | OFFICER | MEMBER
    joined_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_team_member UNIQUE (team_id, player_uuid)
);

CREATE INDEX idx_team_members_player ON team_members (player_uuid);
