-- V4: guild treasury withdrawal approval workflow (docs/07-tenants.md).
-- Money-path tables: aggressively boring names, append-only action audit.

CREATE TABLE withdrawal_requests (
    id            VARCHAR(64) PRIMARY KEY,
    team_id       VARCHAR(64) NOT NULL,
    requester_uuid VARCHAR(64) NOT NULL,
    amount_cents  BIGINT      NOT NULL,
    memo          VARCHAR(256),
    status        VARCHAR(32) NOT NULL,  -- PENDING | AWAITING_UPPER_MANAGEMENT | APPROVED | REJECTED | EXECUTED | FAILED
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_withdrawal_team_status ON withdrawal_requests (team_id, status);

CREATE TABLE approval_actions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  VARCHAR(64) NOT NULL,
    actor_uuid  VARCHAR(64) NOT NULL,
    action      VARCHAR(32) NOT NULL,    -- SUBMITTED | RUBBER_STAMPED | APPROVED | REJECTED | NUDGED
    note        VARCHAR(256),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_approval_actions_request ON approval_actions (request_id);
