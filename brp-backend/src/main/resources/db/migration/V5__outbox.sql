-- V5: backend transactional outbox (docs/06-transactions.md section 3).
-- Business events enqueue in the SAME transaction as the work; the
-- dispatcher delivers at-least-once; consumers dedup by event_id.

CREATE TABLE outbox_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    VARCHAR(64)  NOT NULL,
    event_type  VARCHAR(64)  NOT NULL,
    payload     TEXT         NOT NULL,
    status      VARCHAR(16)  NOT NULL,   -- PENDING | DELIVERED | FAILED
    attempts    INT          NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delivered_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_outbox_event UNIQUE (event_id)
);

CREATE INDEX idx_outbox_status ON outbox_messages (status, id);
