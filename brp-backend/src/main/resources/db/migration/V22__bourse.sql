-- V22: P5 the bourse (docs/14 §6). Batch-auction exchange, listed mint,
-- warehouse with an append-only movement log. Money legs ride the existing
-- ledger accounts; items get the same discipline the ledger has.

-- The catalog: every tradable identity. Listing state is governance-owned —
-- the mod catalog push may never touch it (docs/14 §5).
CREATE TABLE exchange_items (
    item_id      VARCHAR(191) PRIMARY KEY,
    display_name VARCHAR(191) NOT NULL,
    listed_state VARCHAR(12)  NOT NULL DEFAULT 'DEFAULT', -- DEFAULT|LISTED|BLOCKED
    ref_cents    BIGINT       NOT NULL,
    pinned       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- The mint's founding listing (docs/14 §4): the demonstration row, priced
-- at the emerald leg rate. Unpinned — it crawls, and the peg band argues.
INSERT INTO exchange_items (item_id, display_name, listed_state, ref_cents, pinned)
VALUES ('minecraft:emerald', 'Emerald', 'LISTED', 6400, FALSE);

-- Materialized custody; the movement log below is the truth.
CREATE TABLE warehouse (
    tenant_id VARCHAR(64)  NOT NULL,
    item_id   VARCHAR(191) NOT NULL,
    qty_free  BIGINT NOT NULL DEFAULT 0,
    qty_held  BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (tenant_id, item_id)
);

-- Append-only movements (journal_entries discipline, item edition). Every
-- warehouse mutation writes one row; reconciliation reads the sum.
CREATE TABLE exchange_movements (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  VARCHAR(64)  NOT NULL,
    item_id    VARCHAR(191) NOT NULL,
    delta_free BIGINT NOT NULL,
    delta_held BIGINT NOT NULL,
    kind       VARCHAR(16)  NOT NULL,
    ref_id     VARCHAR(128),
    idem_key   VARCHAR(128) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_movements_item ON exchange_movements (item_id, tenant_id);

-- Resting limit orders; BIDs escrow BRC, ASKs hold warehouse stock.
CREATE TABLE exchange_orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     VARCHAR(64)  NOT NULL,
    item_id       VARCHAR(191) NOT NULL,
    idem_key      VARCHAR(128) NOT NULL UNIQUE,
    side          VARCHAR(4)   NOT NULL,               -- ASK | BID
    qty           BIGINT       NOT NULL,
    qty_remaining BIGINT       NOT NULL,
    price_cents   BIGINT       NOT NULL,
    status        VARCHAR(12)  NOT NULL DEFAULT 'NEW', -- NEW|PARTIAL|FILLED|CANCELLED|EXPIRED
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_exchange_orders_book ON exchange_orders
    (item_id, side, status, price_cents, created_at);

-- Withdraw claims: free qty leaves the books on filing, returns on release,
-- the agent confirms after the goods actually moved (docs/14 §8).
CREATE TABLE exchange_claims (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  VARCHAR(64)  NOT NULL,
    item_id    VARCHAR(191) NOT NULL,
    qty        BIGINT       NOT NULL,
    status     VARCHAR(12)  NOT NULL DEFAULT 'PENDING', -- PENDING|CONFIRMED|RELEASED
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- One insert-only guard row per batch: the scheduler's idempotency, the
-- ProfileRun pattern.
CREATE TABLE exchange_batches (
    batch_seq      BIGINT PRIMARY KEY,
    cleared_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    items_cleared  INT    NOT NULL DEFAULT 0,
    trades_cleared INT    NOT NULL DEFAULT 0
);

CREATE TABLE exchange_trades (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_seq    BIGINT       NOT NULL,
    item_id      VARCHAR(191) NOT NULL,
    buyer        VARCHAR(64)  NOT NULL,
    seller       VARCHAR(64)  NOT NULL,
    qty          BIGINT       NOT NULL,
    price_cents  BIGINT       NOT NULL,
    fee_cents    BIGINT       NOT NULL,
    bid_order_id BIGINT,
    ask_order_id BIGINT,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_exchange_trades_item ON exchange_trades (item_id, batch_seq);

-- One row per item per batch: the price observation the peg band and CPI
-- consume (docs/14 §7).
CREATE TABLE exchange_clears (
    batch_seq    BIGINT       NOT NULL,
    item_id      VARCHAR(191) NOT NULL,
    price_cents  BIGINT,
    cleared_qty  BIGINT NOT NULL DEFAULT 0,
    bid_vol      BIGINT NOT NULL DEFAULT 0,
    ask_vol      BIGINT NOT NULL DEFAULT 0,
    surplus      BIGINT NOT NULL DEFAULT 0,
    mint_bid_qty BIGINT NOT NULL DEFAULT 0,
    mint_ask_qty BIGINT NOT NULL DEFAULT 0,
    ref_before   BIGINT,
    ref_after    BIGINT,
    PRIMARY KEY (batch_seq, item_id)
);
