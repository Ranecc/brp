-- V7: daily economy observability (docs/03-economy.md section 7, P1).
-- M (money mass), net emission, traded volume, velocity V — per day, per currency.

CREATE TABLE economy_daily (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_date         DATE         NOT NULL,
    currency            VARCHAR(8)   NOT NULL,
    money_mass_cents    BIGINT       NOT NULL DEFAULT 0,
    net_emission_cents  BIGINT       NOT NULL DEFAULT 0,
    traded_volume_cents BIGINT       NOT NULL DEFAULT 0,
    velocity            DOUBLE       NOT NULL DEFAULT 0,
    CONSTRAINT uq_economy_daily UNIQUE (report_date, currency)
);
