-- V19: P4 load plane, tariff table, demand response, credit (docs/13 §2, §4-6).
-- The server's diurnal pulse becomes a first-class, billable time series.

-- One row per UTC minute: the raw material for forecasting AND bond settlement.
-- mspt_avg is an incremental mean over heartbeat samples in the minute; the
-- rest are maxima (a one-second spike is load, averages forgive too much).
CREATE TABLE load_samples (
    bucket_minute TIMESTAMP    NOT NULL,        -- "minute" is reserved in H2
    sample_count  INT          NOT NULL DEFAULT 0,
    mspt_avg      DOUBLE       NOT NULL DEFAULT 0,
    mspt_max      DOUBLE       NOT NULL DEFAULT 0,
    player_max    INT          NOT NULL DEFAULT 0,
    entity_max    INT          NOT NULL DEFAULT 0,
    chunk_max     INT          NOT NULL DEFAULT 0,
    forced_max    INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (bucket_minute)
);

-- Durable minute-of-day seasonality: EWMA of mspt per minute, refreshed once
-- per day. The forecaster's prior; the live EWMA is the correction.
CREATE TABLE load_profile (
    minute_of_day INT         NOT NULL,        -- 0..1439
    ewma_mspt     DOUBLE      NOT NULL DEFAULT 0,
    sample_days   INT         NOT NULL DEFAULT 0,
    PRIMARY KEY (minute_of_day)
);

-- Insert-only idem guard: the daily profile refresh runs exactly once per day.
CREATE TABLE load_profile_runs (
    refresh_date DATE PRIMARY KEY,
    ran_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Versioned time-of-use tariff (docs/13 §4). Version 0 is boot-config-owned
-- (re-derived from the legacy brp.chunk.billing.peak-* keys on every start);
-- versions 1+ are console/API-owned and immutable once superseded.
CREATE TABLE tariff_windows (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      INT         NOT NULL,
    day_of_week  INT         NOT NULL,          -- -1 = all days, else 1=MON..7=SUN
    start_minute INT         NOT NULL,          -- minute of day, inclusive
    end_minute   INT         NOT NULL,          -- exclusive; may exceed 1440 via wrap start>end
    multiplier_pct INT       NOT NULL,          -- 100 = par; 200 = double; 60 = valley
    label        VARCHAR(8)  NOT NULL           -- VALLEY | SHOULDER | PEAK
);
CREATE INDEX idx_tariff_version ON tariff_windows (version);

-- Deferrable load registry (docs/13 §5): tenant-declared flexible work.
CREATE TABLE deferred_jobs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      VARCHAR(64) NOT NULL,
    idem_key       VARCHAR(128) NOT NULL UNIQUE,
    resource       VARCHAR(32)  NOT NULL,
    quantity       BIGINT       NOT NULL DEFAULT 0,
    est_minutes    BIGINT       NOT NULL,
    earliest       TIMESTAMP    NOT NULL,
    deadline       TIMESTAMP    NOT NULL,
    status         VARCHAR(12)  NOT NULL DEFAULT 'FILED',  -- FILED|AWARDED|RUNNING|DONE|SHED|EXPIRED|CANCELLED
    awarded_start  TIMESTAMP,
    awarded_minutes BIGINT      NOT NULL DEFAULT 0,
    window_seq     INT          NOT NULL DEFAULT 0,
    shed_count     INT          NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_deferred_jobs_tenant ON deferred_jobs (tenant_id, status);

-- Credit lines (docs/13 §6): BRC-denominated debt, drawn implicitly when a
-- posting would overdraw cash. The ledger still never mints.
CREATE TABLE credit_lines (
    tenant_id      VARCHAR(64) PRIMARY KEY,
    limit_cents    BIGINT      NOT NULL DEFAULT 0,
    drawn_cents    BIGINT      NOT NULL DEFAULT 0,
    status         VARCHAR(12) NOT NULL DEFAULT 'GOOD',  -- GOOD|WATCH|RESTRICTED|DEFAULTED
    status_since   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    annual_rate_pct INT         NOT NULL DEFAULT 12,
    restricted_since TIMESTAMP WITH TIME ZONE,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Every credit action is a row: an audit trail or it didn't happen.
CREATE TABLE credit_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    VARCHAR(64) NOT NULL,
    kind         VARCHAR(12) NOT NULL,   -- DRAW|REPAY|INTEREST|LIMIT_SET|STATUS
    amount_cents BIGINT      NOT NULL DEFAULT 0,
    memo         VARCHAR(200) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_credit_events_tenant ON credit_events (tenant_id, id);
