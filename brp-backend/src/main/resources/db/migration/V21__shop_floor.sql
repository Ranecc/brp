-- V21: P4 shop floor (docs/13 §9) — the downtime ledger, OEE's raw material,
-- the asset registry, and the work-order costing stamp.

CREATE TABLE downtime_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  VARCHAR(64) NOT NULL,
    machine    VARCHAR(128) NOT NULL,          -- machine ref or '*' for grid actions
    reason     VARCHAR(24)  NOT NULL,          -- CHUNK_UNLOADED|HOPPER_JAM|NO_POWER|MANUAL|DR_SHED|CREDIT_CUTOFF
    idem_key   VARCHAR(160) NOT NULL UNIQUE,
    since      TIMESTAMP    NOT NULL,
    until      TIMESTAMP    NOT NULL,
    minutes    BIGINT       NOT NULL
);
CREATE INDEX idx_downtime_tenant ON downtime_events (tenant_id, since);

CREATE TABLE assets (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        VARCHAR(64)  NOT NULL,
    kind             VARCHAR(32)  NOT NULL,    -- base | rail_line | hall | golem | machine | ...
    label            VARCHAR(128) NOT NULL,
    location_chunk   VARCHAR(64),
    cost_basis_cents BIGINT       NOT NULL DEFAULT 0,
    status           VARCHAR(12)  NOT NULL DEFAULT 'IN_SERVICE',
    acquired_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_assets_tenant ON assets (tenant_id, id);

-- The CO recommendation (docs/10 business map): completion cost stamped at
-- handover — materials as reported, machine time priced by the levy minutes
-- already in the books. Schema now so P5 reports are free.
CREATE TABLE workorder_costs (
    tenant_id           VARCHAR(64) NOT NULL,
    workorder_ref       VARCHAR(128) NOT NULL,
    material_cost_cents BIGINT      NOT NULL DEFAULT 0,
    machine_cost_cents  BIGINT      NOT NULL DEFAULT 0,
    stamped_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (tenant_id, workorder_ref)
);
