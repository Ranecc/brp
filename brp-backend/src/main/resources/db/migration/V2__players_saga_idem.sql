-- V2: player identity sync (agent pulls uuid/name from the MC server),
-- generic @Idempotent store, @Compensable saga audit rows.

CREATE TABLE players (
    uuid      VARCHAR(64) PRIMARY KEY,   -- dashed v4 (online) or offline type-3, stored verbatim
    name      VARCHAR(32) NOT NULL,
    first_seen TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE player_name_history (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid      VARCHAR(64) NOT NULL,
    old_name  VARCHAR(32),
    new_name  VARCHAR(32),
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_player_history_uuid ON player_name_history (uuid);

CREATE TABLE idem_store (
    idem_key      VARCHAR(160) PRIMARY KEY,
    response_json TEXT,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE saga_instances (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    saga         VARCHAR(64)  NOT NULL,
    step         VARCHAR(64)  NOT NULL,
    correlation  VARCHAR(128),
    compensation VARCHAR(64),
    state        VARCHAR(16)  NOT NULL,   -- RUNNING | DONE | FAILED
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_saga_correlation ON saga_instances (correlation);
