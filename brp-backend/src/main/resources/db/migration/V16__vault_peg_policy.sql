-- V16: P3 money creation & anchors (docs/12 sections 8-10):
-- the vault, the peg legs, and the policy-request queue.

CREATE TABLE peg_state (
    leg                VARCHAR(8) PRIMARY KEY,   -- emerald | quota
    rate               DOUBLE      NOT NULL,     -- BRC per stack / per quota-minute
    band_low           DOUBLE      NOT NULL,
    band_high          DOUBLE      NOT NULL,
    out_of_band_streak INT         NOT NULL DEFAULT 0,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

