    ('quota',   10.0,  9.5, 10.5);

CREATE TABLE peg_history (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leg        VARCHAR(8)  NOT NULL,
    old_rate   DOUBLE      NOT NULL,
    new_rate   DOUBLE      NOT NULL,
    request_id BIGINT,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE vault_registrations (
    tenant_id     VARCHAR(64)  NOT NULL,
    container_ref VARCHAR(128) NOT NULL,
    item_id       VARCHAR(255) NOT NULL,
    registered_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (tenant_id, container_ref)
);

CREATE TABLE vault_movements (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   VARCHAR(64)  NOT NULL,
    container_ref VARCHAR(128) NOT NULL,
    direction   VARCHAR(16)  NOT NULL,   -- OUT | REVOKE
    item_id     VARCHAR(255) NOT NULL,
    qty         BIGINT       NOT NULL,
    correlation VARCHAR(128) NOT NULL,
    at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE policy_requests (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          VARCHAR(32)  NOT NULL,   -- repeg-vote | peg-band-emergency
    payload_json  TEXT         NOT NULL,
    status        VARCHAR(16)  NOT NULL DEFAULT 'PENDING',   -- PENDING | APPROVED | REJECTED
    requested_by  VARCHAR(64),
    decided_by    VARCHAR(64),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at    TIMESTAMP WITH TIME ZONE
);
