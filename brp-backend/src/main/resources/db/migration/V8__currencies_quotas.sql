CREATE TABLE quota_buckets (
    tenant_id    VARCHAR(64)  NOT NULL,
    resource     VARCHAR(32)  NOT NULL,   -- machine_slot | chunk_ticket | ...
    limit_amount BIGINT       NOT NULL DEFAULT 0,   -- 0 = unlimited licensing
    used         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_quota PRIMARY KEY (tenant_id, resource)
);

CREATE TABLE chunk_incidents (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   VARCHAR(64),
    dimension   VARCHAR(64),
    chunk       VARCHAR(64) NOT NULL,
    cost_score  DOUBLE      NOT NULL,
    status      VARCHAR(16) NOT NULL DEFAULT 'OPEN',   -- OPEN | HANDLED (by a human, presumably)
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
