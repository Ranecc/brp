-- V8: currency registry (owner-configured) + compute quota domain
-- (docs/03 section 6: machine placement is licensed by compute quota;
-- violations PAGE the admins — handling is above this system's pay grade).

CREATE TABLE currencies (
    code       VARCHAR(8)  PRIMARY KEY,
    name       VARCHAR(64) NOT NULL,
    symbol     VARCHAR(8)  NOT NULL,
    decimals   INT         NOT NULL DEFAULT 2,
    status     VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',   -- ACTIVE | RETIRED
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- The base currency ships pre-registered; owners add more from the web console.
